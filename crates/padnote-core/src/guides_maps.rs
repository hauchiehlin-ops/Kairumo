//! 空白地圖紙（地理筆記用）：世界、俄羅斯與中亞、台灣的輪廓。
//!
//! # 為什麼是紙張，不是素材圖庫的一張圖
//!
//! 學生的用法是「一頁一張空白地圖，在上面著色、標註」（實測仿製的地理筆記就是這樣）。
//! 做成紙張樣板的引導線，地圖就是這一頁的結構：不會被誤點選、拖走，兩個平台畫的是
//! 核心給的同一串線段（`page_guides`），平台不必再各寫一份繪圖程式。
//!
//! # 輪廓資料
//!
//! 經緯度（度），依常識手繪的**簡化**外框 —— 給課堂描圖、著色與標註用，不是測繪用地圖。
//! 沒有引用任何外部地圖資料，沒有授權問題。投影是等距長方（經度依中緯度餘弦縮放），
//! 一律保持長寬比，放在頁面上半部。

/// 一條輪廓：`true` = 封閉（海岸線、湖），`false` = 開放的折線（國界）。
pub(crate) type Ring = (&'static [(f32, f32)], bool);

/// 一張地圖：範圍（經度、緯度）與輪廓。
pub(crate) struct MapSheet {
    pub lon: (f32, f32),
    pub lat: (f32, f32),
    pub rings: &'static [Ring],
}

/// 依紙張識別字取地圖。不是地圖紙回 `None`。
pub(crate) fn map_for(paper_id: &str) -> Option<&'static MapSheet> {
    match paper_id {
        "map_world" => Some(&WORLD),
        "map_russia_central_asia" => Some(&RUSSIA_CENTRAL_ASIA),
        "map_taiwan" => Some(&TAIWAN),
        _ => None,
    }
}

/// 把地圖投影到頁面比例座標（0–1），回傳每一段線（x1, y1, x2, y2）。
///
/// 地圖寬度用滿左右邊界之間，高度依長寬比；太高時改以高度為準（不超過頁面的 `max_h`）。
pub(crate) fn map_segments(
    map: &MapSheet,
    width: f32,
    height: f32,
    left: f32,
    right: f32,
    top: f32,
    max_h: f32,
) -> Vec<(f32, f32, f32, f32)> {
    let mid = ((map.lat.0 + map.lat.1) * 0.5).to_radians().cos().max(0.2);
    let span_x = (map.lon.1 - map.lon.0) * mid;
    let span_y = map.lat.1 - map.lat.0;
    // 以頁面像素算長寬比，再換回比例座標。
    let mut box_w = (right - left) * width;
    let mut box_h = box_w * span_y / span_x;
    if box_h > max_h * height {
        box_h = max_h * height;
        box_w = box_h * span_x / span_y;
    }
    let x0 = left * width + ((right - left) * width - box_w) * 0.5;
    let project = |(lon, lat): (f32, f32)| -> (f32, f32) {
        let x = x0 + (lon - map.lon.0) * mid / span_x * box_w;
        let y = top * height + (map.lat.1 - lat) / span_y * box_h;
        (x / width, y / height)
    };
    let mut out = Vec::new();
    for (points, closed) in map.rings {
        let n = points.len();
        if n < 2 {
            continue;
        }
        let last = if *closed { n } else { n - 1 };
        for i in 0..last {
            let a = project(points[i]);
            let b = project(points[(i + 1) % n]);
            out.push((a.0, a.1, b.0, b.1));
        }
    }
    out
}

