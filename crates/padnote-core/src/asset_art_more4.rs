// 見 `asset_art_more.rs` 的說明。

fn draw_more4(code: &str, b: &mut Builder) -> bool {
    let (name, p) = split_code(code);
    match name {
        "mold" => mold(b, p),
        "ai_conformal_cooling" => ai_conformal_cooling(b),
        "ai_adaptive_mold" => ai_adaptive_mold(b),
        "sheet" => sheet(b, p),
        "cnc" => cnc(b, p),
        "ai_robotic_forming" => ai_robotic_forming(b),
        "ai_adaptive_toolpath" => ai_adaptive_toolpath(b),
        "finish" => finish(b, p),
        "ai_self_healing_coat" => ai_self_healing_coat(b),
        "ai_structural_color" => ai_structural_color(b),
        "pipe" => pipe(b, p),
        "pneu" => pneu(b, p),
        "ai_soft_actuator" => ai_soft_actuator(b),
        "ai_microfluidic" => ai_microfluidic(b),
        _ => return false,
    }
    true
}

