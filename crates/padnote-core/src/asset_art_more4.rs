fn ai_soft_actuator(b: &mut Builder) {
    // 軟體氣動致動器：一排可充氣腔室，充氣後彎曲
    for k in 0..6 {
        b.rounded(70.0 + k as f32 * 38.0, 190.0 - k as f32 * 4.0, 34.0, 50.0, 10.0);
    }
    b.accent(true);
    b.path(vec![m(70.0, 150.0), c(160.0, 100.0, 260.0, 100.0, 330.0, 170.0)]);
    b.poly(&[(318.0, 160.0), (330.0, 170.0), (316.0, 176.0)]);
    b.accent(false);
}

