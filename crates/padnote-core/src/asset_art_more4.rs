fn ai_adaptive_toolpath(b: &mut Builder) {
    // 自適應刀路：依負載改變步距
    b.rect_open(70.0, 70.0, 260.0, 200.0);
    let mut y = 90.0;
    let mut gap = 30.0;
    while y < 260.0 {
        b.poly(&[(90.0, y), (310.0, y)]);
        y += gap;
        gap = (gap - 3.0).max(10.0);
    }
    b.accent(true);
    b.poly(&[(330.0, 90.0), (350.0, 270.0)]);
    b.accent(false);
}

