// 貼紙的圖形本體。由 `ffi_stickers.rs` 以 `include!` 併入 ——
// 它們共用素材線圖那一組 `Builder` 工具，拆成獨立模組只會多一層 `use`。
//
// # 為什麼是自己畫的向量，不是圖檔
//
// 這個專案**完全開源、完全免費**。市面上的貼紙包幾乎都有授權限制，
// 抄進來就是把一個授權問題埋進產品裡。畫成向量還有三個好處：
//
//   * 兩端算繪同一份資料，不會出現「iPad 上的笑臉比較胖」
//   * 縮放不糊 —— 貼紙會被拉大拉小，點陣圖撐不住
//   * 跟著主題配色走（`asset_palette`），深色模式不必另外備一套
//
// 座標一律在 100×100 的方格裡，由 `sticker_canvas_size()` 給出。
// 素材線圖用的是 400×400 —— 貼紙小得多，用同一個尺度的話每個數字都要
// 除以四，而除錯時心算除法是會出錯的。

/// 一個分類底下的貼紙代號。順序就是顯示順序。
///
/// **分類依「使用者想做什麼」分，不是依圖形長相分。** 依長相分的話
/// （圓形類、箭頭類）使用者得先知道自己要找什麼形狀才找得到，
/// 而他心裡想的是「我要標一個重點」。
static CATALOGUE: &[(&str, &[&str])] = &[
    // 標註：批改、審閱、劃重點時用的。
    (
        "annotate",
        &[
            "check",
            "cross",
            "star",
            "exclaim",
            "question",
            "circle_mark",
            "underline",
            "bracket",
        ],
    ),
    // 待辦：清單與進度。
    (
        "task",
        &["checkbox", "checkbox_done", "flag", "bullet", "half_done", "blocked"],
    ),
    // 心情：讀自己的筆記時最常用的一類 —— 標記「這裡有問題」「這裡很讚」。
    (
        "mood",
        &["smile", "frown", "neutral", "heart", "thumb_up", "idea", "hot"],
    ),
    // 標籤：把一段內容框起來、命名、之後找得到。
    (
        "label",
        &["ribbon", "tag", "bookmark", "bubble", "note", "badge"],
    ),
    // 學習：上課與複習。
    (
        "study",
        &["book", "pencil", "clock", "calendar", "formula", "qa"],
    ),
    // 流程：把想法連起來。
    (
        "flow",
        &["arrow_right", "arrow_left", "arrow_up", "arrow_down", "arrow_curve", "branch", "loop"],
    ),
];

/// 畫一張貼紙。認不得的代號回一個空心圓 —— **不是空清單**。
///
/// 空清單會讓格子變成一格空白，而使用者不知道那是沒畫好還是壞掉了。
fn draw_sticker(code: &str) -> Vec<FfiDrawPath> {
    let mut b = Builder::new();
    b.width(6.0);
    match code {
        // ── 標註 ──────────────────────────────────────────────
        "check" => {
            b.accent(true).poly(&[(20.0, 52.0), (42.0, 74.0), (82.0, 26.0)]);
        }
        "cross" => {
            b.accent(true)
                .poly(&[(26.0, 26.0), (74.0, 74.0)])
                .poly(&[(74.0, 26.0), (26.0, 74.0)]);
        }
        "star" => {
            // 五角星。外半徑 38、內半徑 16，從正上方起算。
            let mut pts = Vec::with_capacity(10);
            for i in 0..10 {
                let r = if i % 2 == 0 { 38.0 } else { 16.0 };
                let a = -std::f32::consts::FRAC_PI_2 + i as f32 * std::f32::consts::PI / 5.0;
                pts.push((50.0 + r * a.cos(), 50.0 + r * a.sin()));
            }
            b.accent(true).shape(&pts);
        }
        "exclaim" => {
            b.accent(true)
                .poly(&[(50.0, 20.0), (50.0, 60.0)])
                .circle(50.0, 76.0, 5.0);
        }
        "question" => {
            b.accent(true)
                .path(vec![
                    m(34.0, 36.0),
                    curve_seg((34.0, 18.0), (66.0, 18.0), (66.0, 36.0)),
                    curve_seg((66.0, 50.0), (50.0, 50.0), (50.0, 62.0)),
                ])
                .circle(50.0, 78.0, 5.0);
        }
        "circle_mark" => {
            // 圈出重點。手繪感的橢圓 —— 正圓看起來像系統圖示，不像有人圈的。
            b.accent(true).ellipse(14.0, 26.0, 72.0, 48.0);
        }
        "underline" => {
            b.accent(true).path(vec![
                m(14.0, 60.0),
                curve_seg((34.0, 74.0), (60.0, 46.0), (86.0, 60.0)),
            ]);
        }
        "bracket" => {
            b.poly(&[(66.0, 18.0), (40.0, 18.0), (40.0, 82.0), (66.0, 82.0)]);
        }

        // ── 待辦 ──────────────────────────────────────────────
        "checkbox" => {
            b.rect_open(22.0, 22.0, 56.0, 56.0);
        }
        "checkbox_done" => {
            b.rect_open(22.0, 22.0, 56.0, 56.0)
                .accent(true)
                .poly(&[(34.0, 50.0), (46.0, 64.0), (68.0, 36.0)]);
        }
        "flag" => {
            b.poly(&[(30.0, 16.0), (30.0, 86.0)])
                .accent(true)
                .shape(&[(30.0, 20.0), (76.0, 32.0), (30.0, 46.0)]);
        }
        "bullet" => {
            b.circle(50.0, 50.0, 14.0);
        }
        "half_done" => {
            // 做到一半。半填的圓比「50%」這種字好認，而且不吃語言。
            b.circle(50.0, 50.0, 28.0).accent(true).shape(&[
                (50.0, 22.0),
                (50.0, 78.0),
                (28.0, 68.0),
                (24.0, 40.0),
            ]);
        }
        "blocked" => {
            b.accent(true)
                .circle(50.0, 50.0, 28.0)
                .poly(&[(30.0, 70.0), (70.0, 30.0)]);
        }

        // ── 心情 ──────────────────────────────────────────────
        "smile" => {
            b.circle(50.0, 50.0, 32.0)
                .circle(39.0, 42.0, 3.5)
                .circle(61.0, 42.0, 3.5)
                .path(vec![m(34.0, 58.0), curve_seg((42.0, 72.0), (58.0, 72.0), (66.0, 58.0))]);
        }
        "frown" => {
            b.circle(50.0, 50.0, 32.0)
                .circle(39.0, 42.0, 3.5)
                .circle(61.0, 42.0, 3.5)
                .path(vec![m(34.0, 68.0), curve_seg((42.0, 54.0), (58.0, 54.0), (66.0, 68.0))]);
        }
        "neutral" => {
            b.circle(50.0, 50.0, 32.0)
                .circle(39.0, 42.0, 3.5)
                .circle(61.0, 42.0, 3.5)
                .poly(&[(36.0, 62.0), (64.0, 62.0)]);
        }
        "heart" => {
            b.accent(true).path(vec![
                m(50.0, 78.0),
                curve_seg((18.0, 58.0), (18.0, 30.0), (36.0, 28.0)),
                curve_seg((45.0, 27.0), (50.0, 36.0), (50.0, 40.0)),
                curve_seg((50.0, 36.0), (55.0, 27.0), (64.0, 28.0)),
                curve_seg((82.0, 30.0), (82.0, 58.0), (50.0, 78.0)),
            ]);
        }
        "thumb_up" => {
            b.shape(&[(24.0, 48.0), (36.0, 48.0), (36.0, 82.0), (24.0, 82.0)])
                .path(vec![
                    m(42.0, 48.0),
                    curve_seg((42.0, 30.0), (50.0, 18.0), (56.0, 20.0)),
                    curve_seg((62.0, 22.0), (56.0, 38.0), (58.0, 44.0)),
                    seg(FfiPathVerb::Line, 76.0, 44.0),
                    curve_seg((84.0, 44.0), (84.0, 56.0), (78.0, 58.0)),
                    curve_seg((84.0, 62.0), (80.0, 72.0), (72.0, 74.0)),
                    seg(FfiPathVerb::Line, 42.0, 80.0),
                    seg(FfiPathVerb::Close, 42.0, 48.0),
                ]);
        }
        "idea" => {
            b.circle(50.0, 42.0, 22.0)
                .poly(&[(42.0, 66.0), (58.0, 66.0)])
                .poly(&[(44.0, 76.0), (56.0, 76.0)])
                .accent(true)
                .poly(&[(50.0, 8.0), (50.0, 16.0)])
                .poly(&[(22.0, 20.0), (28.0, 26.0)])
                .poly(&[(78.0, 20.0), (72.0, 26.0)]);
        }
        "hot" => {
            // 火焰＝「這一段最要緊」。
            b.accent(true).path(vec![
                m(50.0, 84.0),
                curve_seg((26.0, 74.0), (30.0, 50.0), (44.0, 40.0)),
                curve_seg((44.0, 52.0), (52.0, 54.0), (54.0, 44.0)),
                curve_seg((66.0, 52.0), (76.0, 66.0), (50.0, 84.0)),
            ]);
        }

        // ── 標籤 ──────────────────────────────────────────────
        "ribbon" => {
            b.shape(&[
                (16.0, 30.0),
                (84.0, 30.0),
                (84.0, 62.0),
                (16.0, 62.0),
            ])
            .poly(&[(16.0, 62.0), (6.0, 74.0), (26.0, 70.0)])
            .poly(&[(84.0, 62.0), (94.0, 74.0), (74.0, 70.0)]);
        }
        "tag" => {
            b.shape(&[
                (18.0, 30.0),
                (62.0, 30.0),
                (84.0, 50.0),
                (62.0, 70.0),
                (18.0, 70.0),
            ])
            .circle(34.0, 50.0, 5.0);
        }
        "bookmark" => {
            b.shape(&[(32.0, 14.0), (68.0, 14.0), (68.0, 86.0), (50.0, 68.0), (32.0, 86.0)]);
        }
        "bubble" => {
            b.rounded(16.0, 22.0, 68.0, 46.0, 10.0)
                .poly(&[(34.0, 68.0), (30.0, 84.0), (48.0, 68.0)]);
        }
        "note" => {
            // 便利貼：右下角折起來。
            b.shape(&[(22.0, 22.0), (78.0, 22.0), (78.0, 62.0), (62.0, 78.0), (22.0, 78.0)])
                .poly(&[(62.0, 78.0), (62.0, 62.0), (78.0, 62.0)]);
        }
        "badge" => {
            b.circle(50.0, 42.0, 24.0)
                .poly(&[(38.0, 62.0), (32.0, 88.0), (50.0, 76.0), (68.0, 88.0), (62.0, 62.0)]);
        }

        // ── 學習 ──────────────────────────────────────────────
        "book" => {
            b.poly(&[(50.0, 28.0), (50.0, 78.0)])
                .shape(&[(50.0, 28.0), (20.0, 34.0), (20.0, 80.0), (50.0, 74.0)])
                .shape(&[(50.0, 28.0), (80.0, 34.0), (80.0, 80.0), (50.0, 74.0)]);
        }
        "pencil" => {
            b.shape(&[(24.0, 76.0), (30.0, 58.0), (70.0, 18.0), (82.0, 30.0), (42.0, 70.0)])
                .poly(&[(30.0, 58.0), (42.0, 70.0)])
                .accent(true)
                .shape(&[(24.0, 76.0), (30.0, 58.0), (42.0, 70.0)]);
        }
        "clock" => {
            b.circle(50.0, 50.0, 30.0)
                .poly(&[(50.0, 50.0), (50.0, 32.0)])
                .poly(&[(50.0, 50.0), (64.0, 58.0)]);
        }
        "calendar" => {
            b.rect_open(20.0, 26.0, 60.0, 54.0)
                .poly(&[(20.0, 42.0), (80.0, 42.0)])
                .poly(&[(34.0, 18.0), (34.0, 32.0)])
                .poly(&[(66.0, 18.0), (66.0, 32.0)]);
        }
        "formula" => {
            b.rect_open(18.0, 30.0, 64.0, 40.0)
                .accent(true)
                .poly(&[(30.0, 50.0), (44.0, 50.0)])
                .poly(&[(37.0, 43.0), (37.0, 57.0)])
                .poly(&[(56.0, 50.0), (70.0, 50.0)]);
        }
        "qa" => {
            b.rounded(14.0, 22.0, 46.0, 34.0, 8.0)
                .rounded(40.0, 46.0, 46.0, 34.0, 8.0);
        }

        // ── 流程 ──────────────────────────────────────────────
        "arrow_right" => {
            b.accent(true)
                .poly(&[(18.0, 50.0), (78.0, 50.0)])
                .poly(&[(60.0, 34.0), (80.0, 50.0), (60.0, 66.0)]);
        }
        "arrow_left" => {
            b.accent(true)
                .poly(&[(82.0, 50.0), (22.0, 50.0)])
                .poly(&[(40.0, 34.0), (20.0, 50.0), (40.0, 66.0)]);
        }
        "arrow_up" => {
            b.accent(true)
                .poly(&[(50.0, 82.0), (50.0, 22.0)])
                .poly(&[(34.0, 40.0), (50.0, 20.0), (66.0, 40.0)]);
        }
        "arrow_down" => {
            b.accent(true)
                .poly(&[(50.0, 18.0), (50.0, 78.0)])
                .poly(&[(34.0, 60.0), (50.0, 80.0), (66.0, 60.0)]);
        }
        "arrow_curve" => {
            b.accent(true)
                .path(vec![m(20.0, 74.0), curve_seg((20.0, 34.0), (60.0, 26.0), (78.0, 34.0))])
                .poly(&[(66.0, 22.0), (82.0, 36.0), (62.0, 44.0)]);
        }
        "branch" => {
            b.poly(&[(22.0, 50.0), (48.0, 50.0)])
                .path(vec![m(48.0, 50.0), curve_seg((64.0, 50.0), (64.0, 26.0), (80.0, 26.0))])
                .path(vec![m(48.0, 50.0), curve_seg((64.0, 50.0), (64.0, 74.0), (80.0, 74.0))]);
        }
        "loop" => {
            b.path(vec![
                m(30.0, 62.0),
                curve_seg((18.0, 38.0), (48.0, 22.0), (66.0, 34.0)),
                curve_seg((82.0, 46.0), (70.0, 72.0), (46.0, 70.0)),
            ])
            .poly(&[(36.0, 50.0), (28.0, 66.0), (44.0, 68.0)]);
        }

        // 認不得的代號：空心圓。不是空清單 ——
        // 空清單會讓格子變成一格空白，而使用者不知道那是沒畫好還是壞掉了。
        _ => {
            b.circle(50.0, 50.0, 30.0);
        }
    }
    b.finish()
}
