/// 一行文字的筆畫。`(x, y)` 是**左上角**，`height` 是字高；字寬約 0.7×字高。
/// 回傳 `(筆畫, 這行的寬度)`。
pub fn text_strokes(text: &str, x: f32, y: f32, height: f32) -> (Vec<Vec<P2>>, f32) {
    let advance = height * 0.72;
    let mut out = Vec::new();
    let mut cx = x;
    for c in text.chars() {
        if c == ' ' {
            cx += advance * 0.6;
            continue;
        }
        for stroke in glyph(c) {
            out.push(
                stroke
                    .into_iter()
                    .map(|(u, v)| (cx + u * advance, y + v * height))
                    .collect(),
            );
        }
        cx += advance;
    }
    (out, cx - x)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_digit_and_section_letter_has_a_glyph() {
        for c in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZagmhxz-.,:+=±×/()°⌀∠⟂∥".chars() {
            assert!(!glyph(c).is_empty(), "{c}");
        }
        assert!(glyph('€').is_empty());
    }

    #[test]
    fn glyph_points_stay_inside_the_unit_box() {
        for c in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZagmhxz-.,:+=±×/()°⌀∠⟂∥".chars() {
            for s in glyph(c) {
                for (u, v) in s {
                    assert!(
                        (0.0..=1.0).contains(&u) && (0.0..=1.0).contains(&v),
                        "{c}: {u},{v}"
                    );
                }
            }
        }
    }

    #[test]
    fn text_width_grows_with_the_number_of_characters() {
        let (_, w1) = text_strokes("5", 0.0, 0.0, 10.0);
        let (_, w3) = text_strokes("120", 0.0, 0.0, 10.0);
        assert!((w3 / w1 - 3.0).abs() < 1e-3);
        let (strokes, _) = text_strokes("A-A", 10.0, 20.0, 8.0);
        assert!(
            strokes
                .iter()
                .flatten()
                .all(|p| p.0 >= 10.0 && p.1 >= 20.0 && p.1 <= 28.0)
        );
    }
}
