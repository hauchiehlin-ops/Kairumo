//! 製圖用的簡易筆畫字形：數字、大寫字母 A–Z、幾個小寫字母（a g h m x z）與製圖符號
//! （⌀ R ° ± × ( ) / . , : + = ∠ ⟂ ∥）。
//!
//! 數字用在尺寸與步驟編號，字母用在剖面標示（A–A）、基準（A B C）、公差帶（H7）與表面粗度（Ra）。
//!
//! 畫在 0…1 的方格裡（y 向下），折線近似曲線。圖紙上的字是**筆畫**（跟著圖層、可被橡皮擦與套索處理），
//! 不是文字方塊 —— 所以隱藏圖層時標註跟著一起隱藏，匯出 PDF 也一定帶得走。

use crate::geom::P2;

/// 橢圓（閉合折線）。
fn ellipse(cx: f32, cy: f32, rx: f32, ry: f32, n: usize) -> Vec<P2> {
    (0..=n)
        .map(|i| {
            let a = i as f32 / n as f32 * std::f32::consts::TAU - std::f32::consts::FRAC_PI_2;
            (cx + rx * a.cos(), cy + ry * a.sin())
        })
        .collect()
}

