import XCTest
@testable import Kairumo

/// 錄音檔名是核心產生的 UUIDv7，前 48 位元是建立時間（毫秒）。
/// 從別台同步下載來的檔案，修改時間是「下載時間」—— 名字不能拿它當錄音時間。
@MainActor
final class RecordingDateFromFileNameTests: XCTestCase {
    /// 組一個 v7 UUID 字串：給定毫秒時間戳。
    private func v7(_ ms: UInt64) -> String {
        let hex = String(format: "%012llx", ms)
        let a = hex.prefix(8), b = hex.suffix(4)
        return "\(a)-\(b)-7abc-8def-0123456789ab"
    }

    func testTheTimestampInAV7NameIsTheRecordingTime() {
        // 2026-10-13 12:50:00 UTC
        let date = Date(timeIntervalSince1970: 1_791_895_800)
        let name = v7(UInt64(date.timeIntervalSince1970 * 1000)) + ".opus"
        let got = NotebookStore.recordingDate(fromFileName: name, fallback: Date(timeIntervalSince1970: 0))
        XCTAssertEqual(got.timeIntervalSince1970, date.timeIntervalSince1970, accuracy: 0.01)
    }

    func testNonV7OrGarbageFallsBack() {
        let fallback = Date(timeIntervalSince1970: 1_700_000_000)
        XCTAssertEqual(NotebookStore.recordingDate(fromFileName: "\(UUID()).opus", fallback: fallback), fallback) // v4
        XCTAssertEqual(NotebookStore.recordingDate(fromFileName: "legacy-take-3.m4a", fallback: fallback), fallback)
        // v7 但時間荒謬（1970）：不採用
        XCTAssertEqual(NotebookStore.recordingDate(fromFileName: v7(1000) + ".opus", fallback: fallback), fallback)
    }

    func testAnAutoGeneratedNameIsRecognisedButAUserNameIsNot() {
        let date = Date(timeIntervalSince1970: 1_791_895_800)
        XCTAssertTrue(NotebookStore.isAutoPlaceholderTitle(
            NotebookStore.defaultQuickRecordingTitle(at: date), recordedDate: date))
        XCTAssertTrue(NotebookStore.isAutoPlaceholderTitle(
            NotebookStore.defaultRecordingTitle(at: date), recordedDate: date))
        XCTAssertFalse(NotebookStore.isAutoPlaceholderTitle("語音", recordedDate: date))
        XCTAssertFalse(NotebookStore.isAutoPlaceholderTitle(
            NotebookStore.defaultQuickRecordingTitle(at: date.addingTimeInterval(3600)), recordedDate: date),
            "時間不同的預設名稱不算（那是別段錄音的名字）")
    }
}
